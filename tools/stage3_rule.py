#!/usr/bin/env python3
"""Stage 3 decision rule, as agreed before any candidate was scored against the truth.

    python3 tools/stage3_rule.py            # -> results/stage3_final.{tsv,md}

Per region and graph:
  - score = ED with nested child alleles left out where a non-reference parent covers them
    (score_haplotypes.py sensitivity.ed_suppress_nested), the median over the graph's replicate calls:
    hybrid200k (the Stage 3 call), hybrid50k (50 kb flank) and hybrid200kids (re-laid node IDs);
  - a candidate is BETTER than mc at a region only if every one of its replicates beats every one of
    mc's, WORSE only if every one loses to every one of mc's; otherwise the region is a tie (inside
    the noise). Regions are compared only where both graphs have >= 2 replicates.
Per stratum: summed median ED, better / worse / tie counts, exact regions (median ED 0).
Decision: a candidate wins at hotspots if it has more reproducibly better than worse hotspots and a
lower summed median ED; it passes the controls unless some control region is reproducibly worse.
Production (genome-wide wgs-mm095 calls, one draw, no replicates) is listed for reference.
"""
import csv
import json
import os
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RES = os.path.join(ROOT, 'results', 'stage3')
GRAPHS = ['mc', 'unit_aware__all', 'mafft_linsi', 'unit_aware', 'poa_abpoa', 'poa_abpoa__all', 'truth']
REPS = ['', '@hybrid50k', '@hybrid200kids']
STRATA = ['hotspot_vntr', 'hotspot_other', 'control_vntr_matched', 'control_vntr_correct', 'control_nontr_sv']
CONTROLS = STRATA[2:]


def score(label, rid):
    p = os.path.join(RES, label, rid + '.json')
    if not os.path.exists(p):
        return None
    d = json.load(open(p))
    if d.get('status') not in (None, 'ok'):
        return None
    return d.get('sensitivity', {}).get('ed_suppress_nested', d['ed'])


def main():
    regions = list(csv.DictReader(open(os.path.join(ROOT, 'regions', 'regions.tsv')), delimiter='\t'))
    strat = {r['region_id']: r['stratum'] for r in regions}
    reps = {g: {} for g in GRAPHS}
    for g in GRAPHS:
        for rid in strat:
            v = [s for s in (score(g + x, rid) for x in REPS) if s is not None]
            if len(v) >= 2:
                reps[g][rid] = v
    prod = {rid: score('genomewide', rid) for rid in strat}
    rows = []
    for s in STRATA:
        ids_mc = [r for r in strat if strat[r] == s and r in reps['mc']]
        for g in GRAPHS:
            ids = [r for r in ids_mc if r in reps[g]]
            med = {r: statistics.median(reps[g][r]) for r in ids}
            mmc = {r: statistics.median(reps['mc'][r]) for r in ids}
            better = [r for r in ids if max(reps[g][r]) < min(reps['mc'][r])]
            worse = [r for r in ids if min(reps[g][r]) > max(reps['mc'][r])]
            pr = [prod[r] for r in ids if prod.get(r) is not None]
            rows.append(dict(stratum=s, graph=g, n=len(ids), ed_sum=sum(med.values()), mc_ed_sum=sum(mmc.values()),
                             production_ed_sum=sum(pr) if len(pr) == len(ids) else None,
                             better=len(better), worse=len(worse), tie=len(ids) - len(better) - len(worse),
                             exact=sum(1 for r in ids if med[r] == 0), mc_exact=sum(1 for r in ids if mmc[r] == 0),
                             better_ids=','.join(better), worse_ids=','.join(worse)))
    keys = list(rows[0].keys())
    with open(os.path.join(ROOT, 'results', 'stage3_final.tsv'), 'w') as f:
        f.write('\t'.join(keys) + '\n')
        for r in rows:
            f.write('\t'.join('' if r[k] is None else str(r[k]) for k in keys) + '\n')
    out = ['# Stage 3 final: local vg call, all regions, replicate rule', '',
           'Generated by `tools/stage3_rule.py` (the rule is in its docstring). ED = edit distance of the called',
           'haplotype pair to HG002 over the span (nested children under a non-reference parent left out),',
           'median over 3 replicate calls; better/worse = every replicate beats / loses to every mc replicate.', '']
    for s in STRATA:
        out += ['## ' + s, '', '| graph | n | summed ED (mc) | better / worse / tie vs mc | exact (mc) |', '|---|---|---|---|---|']
        for r in rows:
            if r['stratum'] == s:
                out.append('| %s | %d | %d (%d) | %d / %d / %d | %d (%d) |' % (
                    r['graph'], r['n'], r['ed_sum'], r['mc_ed_sum'], r['better'], r['worse'], r['tie'],
                    r['exact'], r['mc_exact']))
        pr = [r for r in rows if r['stratum'] == s and r['graph'] == 'mc'][0]
        if pr['production_ed_sum'] is not None:
            out.append('\nProduction (genome-wide calls, one draw) summed ED on the same regions: %d' % pr['production_ed_sum'])
        out.append('')
    # the per-stratum tables above pair each graph with mc on ITS regions; graphs cover different hotspot
    # sets (a graph missing where its aligner ran out of memory), so rows are compared here on shared sets
    for s in ('hotspot_vntr', 'hotspot_other'):
        for gs, lab in ((GRAPHS, 'all seven graphs'), ([g for g in GRAPHS if g != 'poa_abpoa__all'], 'all but poa_abpoa__all')):
            ids = [r for r in strat if strat[r] == s and all(r in reps[g] for g in gs)]
            base = sum(statistics.median(reps['mc'][r]) for r in ids)
            out += ['## %s, regions shared by %s (n=%d; mc summed ED %d)' % (s, lab, len(ids), base), '',
                    '| graph | summed ED | vs mc | better / worse |', '|---|---|---|---|']
            for g in gs[1:]:
                v = sum(statistics.median(reps[g][r]) for r in ids)
                b_ = sum(max(reps[g][r]) < min(reps['mc'][r]) for r in ids)
                w_ = sum(min(reps[g][r]) > max(reps['mc'][r]) for r in ids)
                out.append('| %s | %d | %+.0f%% | %d / %d |' % (g, v, 100 * (v / base - 1) if base else 0, b_, w_))
            out.append('')
    out += ['## Decision', '', '| graph | hotspot VNTR win | other-hotspot win | controls pass | reproducibly worse controls |', '|---|---|---|---|---|']
    for g in GRAPHS[1:]:
        def w(s):
            r = [x for x in rows if x['stratum'] == s and x['graph'] == g][0]
            return 'yes' if (r['better'] > r['worse'] and r['ed_sum'] < r['mc_ed_sum']) else 'no'
        bad = [x['worse_ids'] for x in rows if x['graph'] == g and x['stratum'] in CONTROLS and x['worse']]
        out.append('| %s | %s | %s | %s | %s |' % (g, w('hotspot_vntr'), w('hotspot_other'),
                                                 'no' if bad else 'yes', ', '.join(bad) or '-'))
    open(os.path.join(ROOT, 'results', 'stage3_final.md'), 'w').write('\n'.join(out) + '\n')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
